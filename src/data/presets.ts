/**
 * Flattened view of all presets with their category attached.
 */
export const PRESETS: Preset[] = PRESET_CATEGORIES.flatMap((category) =>
  CATEGORIZED_PRESETS[category].map((preset) => ({
    ...preset,
    category,
  }))
);

/**
 * Find a preset by its unique ID across all categories.
 */
export const getPresetById = (id: string): Preset | undefined => {
  return PRESETS.find((p) => p.id === id);
};
